"""Rollback Generator Engine (Sprint 6 - Task 52).

Produces safe recovery instructions, patch reversal commands, and backout
plans for patches generated by IBM Bob.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any

from app.services.secret_shield import mask_string


@dataclass(frozen=True)
class RollbackPlan:
    """Actionable rollback instructions to safely revert an applied patch."""

    strategy: str
    commands: list[str] = field(default_factory=list)
    precautions: list[str] = field(default_factory=list)
    verification_steps: list[str] = field(default_factory=list)
    database_caution: bool = False

    def to_dict(self) -> dict[str, Any]:
        """Convert rollback plan to dictionary."""
        return {
            "strategy": mask_string(self.strategy),
            "commands": [mask_string(c) for c in self.commands],
            "precautions": [mask_string(p) for p in self.precautions],
            "verification_steps": [mask_string(v) for v in self.verification_steps],
            "database_caution": self.database_caution,
        }


class RollbackGenerator:
    """Synthesizes deterministic recovery strategies for repair patches."""

    @classmethod
    def generate(
        cls,
        target_file: str,
        head_commit: str = "HEAD",
        patch_filename: str = "repair.patch",
        is_database_involved: bool = False,
    ) -> RollbackPlan:
        """Create structured rollback plan.

        Args:
            target_file: File that was modified.
            head_commit: Git commit SHA or ref.
            patch_filename: Name of the generated patch file.
            is_database_involved: Whether database state could be affected.

        Returns:
            RollbackPlan containing commands and precautions.
        """
        short_commit = head_commit[:8] if len(head_commit) >= 8 else head_commit

        commands = [
            "# Option A: Reverse patch application directly",
            f"git apply -R {patch_filename}",
            "# Option B: Revert commit if patch was already committed",
            f"git revert --no-edit {short_commit}",
            "# Clean any untracked artifacts",
            f"git checkout -- {target_file}",
        ]

        precautions = [
            "Ensure no uncommitted working tree changes exist before reversing",
            "Notify team members on active branches touching the modified file",
        ]

        verification_steps = [
            "Run unit and regression test suite (pytest / npm test)",
            f"Verify {target_file} matches previous baseline checksum",
            "Confirm service health checks return 200 OK",
        ]

        if is_database_involved or "db" in target_file.lower():
            precautions.append(
                "CAUTION: Database interactions detected. Verify migration history "
                "before reverting application code."
            )

        return RollbackPlan(
            strategy="Automated reverse-patch & git revert strategy",
            commands=commands,
            precautions=precautions,
            verification_steps=verification_steps,
            database_caution=is_database_involved or "db" in target_file.lower(),
        )

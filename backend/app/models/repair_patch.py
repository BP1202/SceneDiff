"""ORM model for repair_patches table (Sprint 6 - Task 55).

Stores individual Git unified diff patches generated by IBM Bob.
"""

from __future__ import annotations

from datetime import datetime
from typing import TYPE_CHECKING, Any
import uuid

from sqlalchemy import Boolean, DateTime, Enum, ForeignKey, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base
from app.repair.risk import RiskLevel

if TYPE_CHECKING:
    from app.models.repair_report import RepairReport


class RepairPatch(Base):
    """Persisted Git unified diff patch for a repaired file."""

    __tablename__ = "repair_patches"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    report_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("repair_reports.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    target_file: Mapped[str] = mapped_column(
        String(500),
        nullable=False,
    )
    diff_content: Mapped[str] = mapped_column(
        Text,
        nullable=False,
    )
    lines_added: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
    )
    lines_removed: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
    )
    is_validated: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=True,
    )
    risk_level: Mapped[RiskLevel] = mapped_column(
        Enum(
            RiskLevel,
            name="risk_level",
            create_constraint=True,
        ),
        nullable=False,
        index=True,
    )
    validation_notes: Mapped[list[dict[str, Any]]] = mapped_column(
        JSONB,
        nullable=False,
        default=list,
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
    )

    report: Mapped[RepairReport] = relationship(
        "RepairReport",
        back_populates="patches",
    )

"""ORM model for repair_reports table (Sprint 6 - Task 55).

Stores complete AI repair reports generated by IBM Bob 2.0.
"""

from __future__ import annotations

from datetime import datetime
import enum
from typing import TYPE_CHECKING, Any
import uuid

from sqlalchemy import DateTime, Enum, ForeignKey, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import Base
from app.repair.risk import RiskLevel

if TYPE_CHECKING:
    from app.models.repair_patch import RepairPatch


class RepairStatus(enum.StrEnum):
    """Lifecycle status of AI repair operation."""

    PENDING = "PENDING"
    GENERATING = "GENERATING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"


class RepairReport(Base):
    """Persisted AI repair report containing plan, risk, rollback, and patches."""

    __tablename__ = "repair_reports"

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        primary_key=True,
        default=uuid.uuid4,
        nullable=False,
    )
    root_cause_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("root_cause_reports.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    comparison_id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True),
        ForeignKey("behavior_comparisons.id", ondelete="CASCADE"),
        nullable=False,
        index=True,
    )
    repository_name: Mapped[str] = mapped_column(
        String(255),
        nullable=False,
        index=True,
    )
    status: Mapped[RepairStatus] = mapped_column(
        Enum(
            RepairStatus,
            name="repairstatus",
            create_constraint=True,
        ),
        default=RepairStatus.COMPLETED,
        nullable=False,
        index=True,
    )
    summary: Mapped[str] = mapped_column(
        String,
        nullable=False,
    )
    risk_level: Mapped[RiskLevel] = mapped_column(
        Enum(
            RiskLevel,
            name="risk_level",
            create_constraint=True,
        ),
        nullable=False,
        index=True,
    )
    risk_score: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=0,
    )
    repair_confidence: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
        default=80,
    )
    plan: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
    )
    rollback_plan: Mapped[dict[str, Any]] = mapped_column(
        JSONB,
        nullable=False,
        default=dict,
    )
    markdown_report: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        default="",
    )
    pr_summary: Mapped[str] = mapped_column(
        Text,
        nullable=False,
        default="",
    )
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        nullable=False,
        index=True,
    )
    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        server_default=func.now(),
        onupdate=func.now(),
        nullable=False,
    )

    patches: Mapped[list[RepairPatch]] = relationship(
        "RepairPatch",
        back_populates="report",
        cascade="all, delete-orphan",
        lazy="selectin",
    )
